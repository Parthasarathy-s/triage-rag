"""Streamlit UI. Run:  streamlit run app.py   (also the entry point on HF Spaces)."""
import streamlit as st

from src.api import triage

st.set_page_config(page_title="Support Ticket Triage", page_icon="🎫")
st.title("🎫 Support Ticket Triage & Answer Assistant")
st.caption("Classifies a ticket, retrieves similar past answers, and drafts a reply.")

EXAMPLES = [
    "I was charged twice for my last order, can I get a refund?",
    "I forgot my password and can't log in",
    "Where is my package? It was supposed to arrive yesterday",
]
choice = st.selectbox("Try an example", ["(write your own)"] + EXAMPLES)
ticket = st.text_area("Ticket text", value="" if choice.startswith("(") else choice, height=120)
use_llm = st.checkbox("Generate a draft reply (slower)", value=True)

if st.button("Triage", type="primary") and ticket.strip():
    with st.spinner("Working..."):
        try:
            out = triage(ticket.strip(), generate=use_llm)
        except Exception as e:
            st.error(f"Could not process the ticket: {e}")
            st.stop()
    st.metric("Category", out.label, f"confidence {out.confidence:.1%}")
    if out.reply:
        st.subheader("Draft reply")
        st.write(out.reply)
        st.caption(f"Generated by the {out.reply_backend} model")
    with st.expander("Retrieved similar tickets"):
        for s in out.sources:
            st.markdown(f"**{s.question}** (distance {s.distance:.3f})\n\n{s.answer}")
